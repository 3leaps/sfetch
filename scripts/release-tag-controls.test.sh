#!/usr/bin/env bash
# shellcheck disable=SC2016
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd -P)"
while IFS= read -r target; do
	grep -Eq "^${target}:" "$root/Makefile" || {
		echo 'error: release checklist names a missing make target' >&2
		exit 1
	}
done < <(grep -oE 'make [a-z][a-z0-9-]+' "$root/RELEASE_CHECKLIST.md" | awk '{print $2}' | sort -u)
grep -Eq 'git -c gpg\.format=openpgp' "$root/scripts/release-tag.sh" || {
	echo 'error: signed tag must force OpenPGP (gpg.format=openpgp)' >&2
	exit 1
}
scratch="$(cd "$(mktemp -d)" && pwd -P)"
trap 'rm -rf "$scratch"' EXIT
mkdir -p "$scratch/anchor-stage" "$scratch/anchor-dest"
for ext in txt ndjson; do
	printf 'new\n' >"$scratch/anchor-stage/expected-fingerprints.$ext"
	printf 'old\n' >"$scratch/anchor-dest/expected-fingerprints.$ext"
done
if "$root/scripts/install-release-anchors.sh" \
	"$scratch/anchor-stage" "$scratch/anchor-dest" >/dev/null 2>&1; then
	echo 'error: expected overwrite refusal' >&2
	exit 1
fi
for ext in txt ndjson; do
	[[ "$(cat "$scratch/anchor-dest/expected-fingerprints.$ext")" == old ]]
done
rm -f "$scratch/anchor-dest"/expected-fingerprints.*
if SFETCH_TEST_FAIL_ANCHOR_INSTALL=1 "$root/scripts/install-release-anchors.sh" \
	"$scratch/anchor-stage" "$scratch/anchor-dest" >/dev/null 2>&1; then
	echo 'error: expected pair rollback' >&2
	exit 1
fi
for ext in txt ndjson; do
	[[ ! -e "$scratch/anchor-dest/expected-fingerprints.$ext" ]]
done
"$root/scripts/install-release-anchors.sh" "$scratch/anchor-stage" "$scratch/anchor-dest"
for ext in txt ndjson; do
	[[ "$(cat "$scratch/anchor-dest/expected-fingerprints.$ext")" == new ]]
done
if "$root/scripts/install-release-anchors.sh" \
	"$scratch/anchor-stage" "$scratch/anchor-dest" >/dev/null 2>&1; then
	echo 'error: second install overwrote existing anchors' >&2
	exit 1
fi
for ext in txt ndjson; do
	[[ "$(cat "$scratch/anchor-dest/expected-fingerprints.$ext")" == new ]]
done
mkdir -p "$scratch/v1.2.3"
printf 'Release v1.2.3\n' >"$scratch/v1.2.3/message.txt"
export SFETCH_RELEASE_TAG=v1.2.3
export SFETCH_TAG_MESSAGE_DIR="$scratch/v1.2.3"
export SFETCH_TAGGER_NAME='3 Leaps Infosec Team'
export SFETCH_TAGGER_EMAIL='infosec@3leaps.net'
source "$root/scripts/release-tag-common.sh"
expect_fail() { if "$@" >/dev/null 2>&1; then
	echo "expected rejection: $*" >&2
	exit 1
fi; }
tag_identity
[[ "$(tag_message_file)" == "$scratch/v1.2.3/message.txt" ]]
ln -s "$scratch" "$scratch/symlink-parent"
expect_fail env SFETCH_TAG_MESSAGE_DIR="$scratch/symlink-parent/v1.2.3" bash -c 'source "$1"; tag_message_file' _ "$root/scripts/release-tag-common.sh"
printf 'Release v1.2.3' >"$scratch/v1.2.3/message.txt"
expect_fail tag_message_file
printf 'Release v1.2.3  \n' >"$scratch/v1.2.3/message.txt"
expect_fail tag_message_file
printf 'Generated by <model>\n' >"$scratch/v1.2.3/message.txt"
expect_fail tag_message_file
printf 'Generated by <REPLACE-model>\n' >"$scratch/v1.2.3/message.txt"
expect_fail tag_message_file
printf 'Release v1.2.3\n' >"$scratch/v1.2.3/message.txt"
expect_fail env SFETCH_TAGGER_NAME=$'bad\nname' bash -c 'source "$1"; tag_identity' _ "$root/scripts/release-tag-common.sh"
expect_fail env SFETCH_TAGGER_EMAIL='a<b>' bash -c 'source "$1"; tag_identity' _ "$root/scripts/release-tag-common.sh"
expect_fail env -u SFETCH_TAG_MESSAGE_DIR bash -c 'source "$1"; tag_message_file' _ "$root/scripts/release-tag-common.sh"
expect_fail env SFETCH_TAG_MESSAGE_DIR="$scratch" bash -c 'source "$1"; tag_message_file' _ "$root/scripts/release-tag-common.sh"
export SFETCH_PGP_KEY_ID=0123456789ABCDEF
expect_fail tag_selector_shape
# 40-hex without the trailing '!' must be refused. Deleting '!' from the
# tag_selector_shape regex would accept this value.
export SFETCH_PGP_KEY_ID=0123456789ABCDEF0123456789ABCDEF01234567
export SFETCH_GPG_SIGNING_FINGERPRINT=0123456789ABCDEF0123456789ABCDEF01234567
expect_fail tag_selector_shape
export SFETCH_PGP_KEY_ID=0123456789ABCDEF0123456789ABCDEF01234567!
tag_selector_shape
unset SFETCH_PGP_KEY_ID
expect_fail tag_selector_shape
git init -q -b main "$scratch/repo"
git -C "$scratch/repo" config user.name fixture
git -C "$scratch/repo" config user.email fixture@example.invalid
printf 'x\n' >"$scratch/repo/file"
git -C "$scratch/repo" add file
git -C "$scratch/repo" commit -qm fixture
git -C "$scratch/repo" tag v1.2.3
export SFETCH_PGP_KEY_ID=0123456789ABCDEF0123456789ABCDEF01234567!
(
	cd "$scratch/repo"
	expect_fail tag_verify_object refs/tags/v1.2.3 'Release v1.2.3'
)
mkdir -p "$scratch/bin"
cat >"$scratch/bin/gh" <<'SH'
#!/usr/bin/env bash
[[ "${GH_TEST_FAIL:-0}" == 0 ]] || exit 1
if [[ "$*" == *'rulesets?includes_parents=true&per_page=100'* ]]; then
	cat "$RULESET_LIST"
else
	cat "$RULESET_FIXTURE"
fi
SH
chmod +x "$scratch/bin/gh"
export PATH="$scratch/bin:$PATH" RULESET_FIXTURE="$scratch/ruleset.json" RULESET_LIST="$scratch/list.json"
printf '[[{"id":7,"name":"Unrelated display name","target":"tag","enforcement":"active"}]]\n' >"$RULESET_LIST"
cat >"$RULESET_FIXTURE" <<'JSON'
{"name":"Unrelated display name","source_type":"Organization","source":"3leaps","target":"tag","enforcement":"active","conditions":{"ref_name":{"exclude":[],"include":["refs/tags/v*"]}},"rules":[{"type":"creation"},{"type":"deletion"},{"type":"non_fast_forward"},{"type":"update"}],"bypass_actors":[{"actor_id":null,"actor_type":"OrganizationAdmin","bypass_mode":"always"}]}
JSON
report="$root/scripts/release-inspect-tag-ruleset.sh"
[[ "$("$report" v1.2.3)" == FOUND:* ]]
jq 'del(.bypass_actors)' "$scratch/ruleset.json" >"$scratch/hidden.json"
export RULESET_FIXTURE="$scratch/hidden.json"
[[ "$("$report" v1.2.3)" == UNKNOWN:* ]]
export RULESET_FIXTURE="$scratch/ruleset.json"
jq '.conditions.ref_name.exclude = ["refs/tags/v1.2.3"]' "$RULESET_FIXTURE" >"$scratch/excluded.json"
export RULESET_FIXTURE="$scratch/excluded.json"
[[ "$("$report" v1.2.3)" == ABSENT:* ]]
jq '.conditions.ref_name.exclude = ["~UNSUPPORTED"]' "$scratch/ruleset.json" >"$scratch/unknown.json"
export RULESET_FIXTURE="$scratch/unknown.json"
[[ "$("$report" v1.2.3)" == UNKNOWN:* ]]
jq '.rules = [] | .name = "Tag Publish Protection"' "$scratch/ruleset.json" >"$scratch/empty.json"
export RULESET_FIXTURE="$scratch/empty.json"
[[ "$("$report" v1.2.3)" == ABSENT:* ]]
jq '.enforcement = "disabled" | .name = "Tag Publish Protection"' "$scratch/ruleset.json" >"$scratch/inactive.json"
export RULESET_FIXTURE="$scratch/inactive.json"
[[ "$("$report" v1.2.3)" == ABSENT:* ]]
export RULESET_FIXTURE="$scratch/ruleset.json"
[[ "$(GH_TEST_FAIL=1 "$report" v1.2.3)" == UNKNOWN:* ]]
jq '.bypass_actors = [{"actor_type":"Team","bypass_mode":"always","actor_id":2}]' "$RULESET_FIXTURE" >"$scratch/team-bypass.json"
export RULESET_FIXTURE="$scratch/team-bypass.json"
[[ "$("$report" v1.2.3)" == *'bypass=Team:always'* ]]
jq 'del(.target)' "$scratch/ruleset.json" >"$scratch/incomplete.json"
export RULESET_FIXTURE="$scratch/incomplete.json"
[[ "$("$report" v1.2.3)" == UNKNOWN:* ]]
export RULESET_FIXTURE="$scratch/ruleset.json"
printf '[]\n' >"$RULESET_LIST"
[[ "$("$report" v1.2.3)" == ABSENT:* ]]
printf 'bad json\n' >"$RULESET_LIST"
[[ "$("$report" v1.2.3)" == UNKNOWN:* ]]
printf '[[{"id":7,"target":"tag","enforcement":"active"}]]\n' >"$RULESET_LIST"
export RULESET_FIXTURE="$scratch/ruleset.json"
git -C "$scratch/repo" tag -d v1.2.3 >/dev/null
git -C "$scratch/repo" update-ref refs/remotes/origin/main "$(git -C "$scratch/repo" rev-parse HEAD)"
tag_expected_message >"$scratch/expected-message"
cmp -s "$scratch/expected-message" "$scratch/v1.2.3/message.txt"
printf 'Changed message\n' >"$scratch/wrong-message"
(
	cd "$scratch/repo"
	GIT_COMMITTER_NAME="$SFETCH_TAGGER_NAME" GIT_COMMITTER_EMAIL="$SFETCH_TAGGER_EMAIL" \
		git tag -a --cleanup=verbatim v1.2.3 -F "$scratch/expected-message"
)
(
	cd "$scratch/repo"
	tag_verify_object refs/tags/v1.2.3 "$scratch/expected-message"
)
(
	cd "$scratch/repo"
	expect_fail tag_verify_object refs/tags/v1.2.3 "$scratch/wrong-message"
)
printf 'Release v1.2.3\n\n' >"$scratch/extra-blank-lines"
(
	cd "$scratch/repo"
	GIT_COMMITTER_NAME="$SFETCH_TAGGER_NAME" GIT_COMMITTER_EMAIL="$SFETCH_TAGGER_EMAIL" \
		git tag -fa --cleanup=verbatim v1.2.3 -F "$scratch/extra-blank-lines" >/dev/null
	expect_fail tag_verify_object refs/tags/v1.2.3 "$scratch/expected-message"
)
# Throwaway GPG home only: refuse the default homedir (never touch real keys).
fake_home="$scratch/fake-home"
mkdir -p "$fake_home/.gnupg"
chmod 700 "$fake_home/.gnupg"
export SFETCH_GPG_SIGNING_FINGERPRINT=0CACA49B3119B6BC12B2CA11B9B485F294B9FE07
export SFETCH_PGP_KEY_ID=0123456789ABCDEF0123456789ABCDEF01234567!
reject_default_home() {
	local path="$1"
	export HOME="$fake_home"
	export SFETCH_GPG_HOMEDIR="$path"
	set +e
	out="$(tag_bind_operator_gnupg_home 2>&1)"
	rc=$?
	set -e
	[[ "$rc" -ne 0 ]]
	[[ "$out" == *'must not be the default homedir'* ]]
}
reject_default_home "$fake_home/.gnupg"
reject_default_home "$fake_home/.gnupg/"
reject_default_home "$fake_home/./.gnupg"
mkdir -p "$fake_home/tmp/nested"
reject_default_home "$fake_home/tmp/nested/../../.gnupg"
reject_default_home "$fake_home/tmp/../.gnupg"
(
	export HOME="$fake_home"
	export SFETCH_GPG_HOMEDIR="$fake_home/.gnupg"
	expect_fail tag_bind_operator_gnupg_home
)
throwaway="$scratch/gnupg-throwaway"
mkdir -m 700 "$throwaway"
(
	export HOME="$fake_home"
	unset GNUPGHOME
	export SFETCH_GPG_HOMEDIR="$throwaway"
	tag_bind_operator_gnupg_home
	# Source home is validated only; signing must not bind to it.
	[[ "${GNUPGHOME:-}" != "$throwaway" ]]
	[[ "$(tag_stat_mode "$throwaway")" == 700 ]]
)
# Existing non-0700 operator dirs are refused (do not chmod them into compliance).
mode755="$scratch/inherited-0755"
mkdir -m 755 "$mode755"
(
	export HOME="$fake_home"
	export SFETCH_GPG_HOMEDIR="$mode755"
	set +e
	out="$(tag_bind_operator_gnupg_home 2>&1)"
	rc=$?
	set -e
	[[ "$rc" -ne 0 ]]
	[[ "$out" == *'mode 0700'* ]]
	[[ "$(tag_stat_mode "$mode755")" == 755 ]]
)
# Relative symlink to an inherited 0755 home must be refused (do not follow).
ln -s "$mode755" "$scratch/rel-link"
(
	export HOME="$fake_home"
	export SFETCH_GPG_HOMEDIR="./rel-link"
	expect_fail tag_bind_operator_gnupg_home
)
ln -s "$mode755" "$scratch/abs-link"
(
	export HOME="$fake_home"
	export SFETCH_GPG_HOMEDIR="$scratch/abs-link"
	expect_fail tag_bind_operator_gnupg_home
)
tag_fresh_verify_gnupg_home
[[ -d "$TAG_VERIFY_GNUPGHOME" && ! -L "$TAG_VERIFY_GNUPGHOME" ]]
[[ "$(tag_stat_mode "$TAG_VERIFY_GNUPGHOME")" == 700 ]]
verify_home="$TAG_VERIFY_GNUPGHOME"
tag_discard_verify_home
[[ ! -e "$verify_home" ]]
# Signing uses a fresh 0700 temp home, never the operator directory.
(
	export HOME="$fake_home"
	unset GNUPGHOME
	export SFETCH_GPG_HOMEDIR="$throwaway"
	tag_fresh_signing_gnupg_home
	[[ -n "$TAG_SIGN_GNUPGHOME" ]]
	[[ "$TAG_SIGN_GNUPGHOME" != "$throwaway" ]]
	[[ "$TAG_SIGN_GNUPGHOME" != "$fake_home/.gnupg" ]]
	[[ -d "$TAG_SIGN_GNUPGHOME" && ! -L "$TAG_SIGN_GNUPGHOME" ]]
	[[ "$(tag_stat_mode "$TAG_SIGN_GNUPGHOME")" == 700 ]]
	sign_home="$TAG_SIGN_GNUPGHOME"
	tag_discard_signing_home
	[[ ! -e "$sign_home" ]]
)
# Isolated import: signing GNUPGHOME is a temp copy, then discarded.
op_home="$scratch/op-sign"
mkdir -m 700 "$op_home"
gpg --homedir "$op_home" --batch --pinentry-mode loopback --passphrase '' \
	--quick-gen-key 'sign@test.invalid' ed25519 sign never >/dev/null 2>&1
op_primary="$(gpg --homedir "$op_home" --with-colons --fingerprint sign@test.invalid | awk -F: '/^fpr:/ {print $10; exit}')"
(
	export HOME="$fake_home"
	unset GNUPGHOME
	export SFETCH_GPG_HOMEDIR="$op_home"
	export SFETCH_PGP_KEY_ID="${op_primary}!"
	tag_prepare_signing_home
	[[ "$GNUPGHOME" == "$TAG_SIGN_GNUPGHOME" ]]
	[[ "$GNUPGHOME" != "$op_home" ]]
	[[ -d "$op_home" ]]
	sign_home="$TAG_SIGN_GNUPGHOME"
	tag_discard_signing_home
	[[ ! -e "$sign_home" ]]
	[[ -d "$op_home" ]]
)
gpgconf --homedir "$op_home" --kill all >/dev/null 2>&1 || true
if ! python3 - "$root/scripts/release-tag.sh" <<'PY'
from pathlib import Path
import sys
text = Path(sys.argv[1]).read_text()
trap = text.find("trap 'tag_cleanup_homes")
selector = text.find("tag_key_selector")
signing = text.find("tag_prepare_signing_home")
if trap < 0 or selector < 0 or signing < 0 or not (trap < selector < signing):
    raise SystemExit(f'order trap={trap} selector={selector} signing={signing}')
PY
then
	echo 'error: release-tag.sh must arm cleanup before creating GnuPG homes' >&2
	exit 1
fi
grep -q 'tag_cleanup_homes' "$root/scripts/release-tag.sh" || {
	echo 'error: signed-tag EXIT trap must discard signing and verify homes' >&2
	exit 1
}
echo '[ok] signed-tag negative controls passed'
